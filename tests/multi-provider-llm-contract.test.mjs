test('ChatGPT login is exposed without exposing tokens and the Python review entry is gone', () => {
  const main = read('src/main/index.ts')
  const preload = read('src/preload/index.ts')
  const globalTypes = read('src/renderer/src/global.d.ts')
  const app = read('src/renderer/src/App.tsx')
  assert.match(main, /llm:chatgpt-login/)
  assert.match(main, /shell\.openExternal\(url\)/)
  assert.match(preload, /startChatGptLogin/)
  assert.match(preload, /logoutChatGpt/)
  assert.match(globalTypes, /startChatGptLogin/)
  assert.match(app, /ChatGPT 登录/)
  assert.match(app, /systemProfile\.llmConnection\.ready/)
  const loginBridge = preload.match(/startChatGptLogin:[\s\S]*?logoutChatGpt:[^\n]+/)?.[0] ?? ''
  assert.doesNotMatch(loginBridge, /accessToken|refreshToken/)
  assert.equal(existsSync(join(root, 'scripts/review_game.py')), false)
  assert.equal(existsSync(join(root, 'src/main/services/review.ts')), false)
  assert.doesNotMatch(main, /review:start/)
})
