test('ChatGPT credentials are checked before OAuth and model defaults come from provider discovery', () => {
  const registry = read('src/main/services/llm/providerRegistry.ts')
  const onboarding = read('src/renderer/src/features/onboarding/FirstRunOnboarding.tsx')
  const packageJson = JSON.parse(read('package.json'))
  assert.match(registry, /connectionState\(profile\.id\)/)
  assert.match(registry, /if \(state\.ready\)/)
  assert.match(registry, /visionModels\.find\(\(model\) => model\.isDefault\)/)
  assert.match(registry, /recommendedModel: selected\?\.id/)
  assert.match(onboarding, /result\.recommendedModel \|\| result\.models\[0\]/)
  assert.match(onboarding, /已复用 Codex 的 ChatGPT 登录/)
  assert.equal(packageJson.dependencies['@openai/codex'], '0.148.0-alpha.20')
  assert.deepEqual(packageJson.build.asarUnpack, ['node_modules/@openai/codex-*/vendor/**/*'])
})

