test('Codex native runtimes are pinned, checksummed, and copied per package architecture', () => {
  const packageJson = JSON.parse(read('package.json'))
  const manifest = JSON.parse(read('data/codex/manifest.json'))
  const prepare = read('scripts/prepare_codex_runtime.mjs')
  const check = read('scripts/check_codex_runtime.mjs')
  const packagedSmoke = read('scripts/smoke_codex_packaged_runtime.mjs')
  const afterPack = read('build/afterPack.cjs')
  assert.equal(existsSync(join(root, 'data/codex/LICENSE')), true)
  assert.equal(manifest.version, '0.149.0')
  for (const target of ['darwin-arm64', 'darwin-x64', 'win32-x64', 'linux-x64', 'linux-arm64']) {
    assert.match(manifest.targets[target].sha256, /^[a-f0-9]{64}$/)
    assert.ok(manifest.targets[target].bytes > 100_000_000)
  }
  assert.match(prepare, /Codex runtime checksum mismatch/)
  assert.match(check, /failed to report Codex/)
  assert.match(afterPack, /context\.electronPlatformName/)
  assert.match(afterPack, /Codex runtime validation failed/)
  assert.match(afterPack, /data', 'codex', 'LICENSE'/)
  assert.match(packagedSmoke, /packaged Codex license is missing/)
  assert.match(packagedSmoke, /expected packaged target was not found/)
  assert.match(packagedSmoke, /failed to start as Codex/)
  assert.match(packagedSmoke, /validSignedMacRuntime/)
  assert.match(packagedSmoke, /accepted signed package transforms/)
  assert.match(read('.github/workflows/release.yml'), /Verify packaged Codex App Server/)
  assert.match(read('.gitignore'), /data\/codex\/bin/)
  assert.equal(packageJson.scripts['check:codex-runtime'], 'node scripts/check_codex_runtime.mjs --mode=dev')
  assert.equal(packageJson.scripts['smoke:codex-runtime'], 'node scripts/smoke_codex_packaged_runtime.mjs')
})
